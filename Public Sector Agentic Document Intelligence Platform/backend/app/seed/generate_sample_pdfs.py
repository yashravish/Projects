def build_sample_pdfs() -> list[SamplePDF]:
    return [_grant_pdf(), _procurement_pdf(), _policy_pdf()]


def main() -> None:
    """CLI: write the corpus to ./sample-pdfs for inspection."""
    import os

    out = "sample-pdfs"
    os.makedirs(out, exist_ok=True)
    for sample in build_sample_pdfs():
        path = os.path.join(out, sample.filename)
        with open(path, "wb") as fh:
            fh.write(sample.bytes_)
        print(f"wrote {path} ({len(sample.bytes_):,} bytes)")


if __name__ == "__main__":
    main()
