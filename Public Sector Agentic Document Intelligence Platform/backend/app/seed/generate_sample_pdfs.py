"""Generate the synthetic public-sector corpus on disk.

Three documents are produced — a federal grant program announcement, a small
agency procurement notice, and a draft policy memo — each with realistic
section structure, tables, and prose so the retrieval pipeline has actual
text to chunk and embed.

Generated bytes are deterministic across runs (no timestamps in content, no
random IDs) so the SHA256 of each PDF is stable. Idempotency in `seed_data`
relies on that.
"""
from __future__ import annotations

import io
from dataclasses import dataclass

from reportlab import rl_config
from reportlab.lib import colors
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

# Force ReportLab to omit creation timestamp + per-render document ID so
# repeated renders of identical content produce byte-identical PDFs (and
# therefore identical SHA256 hashes — the dedupe path in document_service
# depends on this).
rl_config.invariant = 1


@dataclass(frozen=True)
class SamplePDF:
    filename: str
    title: str
    bytes_: bytes


def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle(
            "DocTitle",
            parent=base["Title"],
            fontName="Times-Bold",
            fontSize=18,
            leading=22,
            spaceAfter=18,
        ),
        "h1": ParagraphStyle(
            "H1",
            parent=base["Heading1"],
            fontName="Times-Bold",
            fontSize=13,
            leading=16,
            spaceBefore=12,
            spaceAfter=8,
        ),
        "body": ParagraphStyle(
            "Body",
            parent=base["BodyText"],
            fontName="Times-Roman",
            fontSize=10.5,
            leading=14,
            spaceAfter=8,
        ),
        "small": ParagraphStyle(
            "Small",
            parent=base["BodyText"],
            fontName="Times-Italic",
            fontSize=9,
            leading=12,
            textColor=colors.grey,
        ),
    }


def _render(title: str, blocks: list[object]) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=LETTER,
        leftMargin=0.9 * inch,
        rightMargin=0.9 * inch,
        topMargin=0.9 * inch,
        bottomMargin=0.9 * inch,
        title=title,
        author="PublicSector ADIP — Sample Corpus",
    )
    doc.build(blocks)
    return buf.getvalue()


